CREATE TABLE departments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_department_id BIGINT REFERENCES departments (id),
    name                 VARCHAR NOT NULL
);

CREATE TABLE employees (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments (id),
    name          VARCHAR NOT NULL
);

CREATE TABLE goal_statuses (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL
);

CREATE TABLE goals (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_goal_id       BIGINT REFERENCES goals (id),
    assignee_employee_id BIGINT REFERENCES employees (id),
    status_id            BIGINT NOT NULL REFERENCES goal_statuses (id),
    end_date             DATE
);

CREATE TABLE key_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id      BIGINT NOT NULL REFERENCES goals (id),
    target_value NUMERIC,
    fact_value   NUMERIC,
    weight       NUMERIC,
    updated_date DATE
);

CREATE TABLE rules (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR NOT NULL,
    severity VARCHAR NOT NULL
);

CREATE TABLE runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status        VARCHAR NOT NULL,
    snapshot_date DATE    NOT NULL
);

CREATE TABLE run_problems (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id  BIGINT NOT NULL REFERENCES runs (id),
    rule_id BIGINT NOT NULL REFERENCES rules (id),
    goal_id BIGINT NOT NULL REFERENCES goals (id)
);

CREATE INDEX idx_run_problems_run_id ON run_problems (run_id);
